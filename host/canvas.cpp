bool font_has_glyph(char c) { return glyph(c) != nullptr; }

Canvas::Canvas(int w, int h) : w_(w), h_(h), px_(size_t(w) * h * 4, 0) {}

void Canvas::clear(Rgba c) {
    for (size_t i = 0; i < px_.size(); i += 4) {
        px_[i] = uint8_t(c >> 24);
        px_[i + 1] = uint8_t(c >> 16);
        px_[i + 2] = uint8_t(c >> 8);
        px_[i + 3] = uint8_t(c);
    }
}

void Canvas::blend(int x, int y, Rgba c) {
    if (x < 0 || y < 0 || x >= w_ || y >= h_) return;
    uint8_t* p = &px_[(size_t(y) * w_ + x) * 4];
    unsigned a = c & 0xFF;
    const unsigned src[4] = {(c >> 24) & 0xFF, (c >> 16) & 0xFF, (c >> 8) & 0xFF, 255};
    for (int i = 0; i < 3; ++i) p[i] = uint8_t((src[i] * a + p[i] * (255 - a) + 127) / 255);
    p[3] = uint8_t(a + p[3] * (255 - a) / 255);
}

void Canvas::fill_rect(int x, int y, int w, int h, Rgba c) {
    for (int yy = y; yy < y + h; ++yy)
        for (int xx = x; xx < x + w; ++xx) blend(xx, yy, c);
}

void Canvas::frame_rect(int x, int y, int w, int h, int t, Rgba c) {
    fill_rect(x, y, w, t, c);
    fill_rect(x, y + h - t, w, t, c);
    fill_rect(x, y + t, t, h - 2 * t, c);
    fill_rect(x + w - t, y + t, t, h - 2 * t, c);
}

void Canvas::progress(int x, int y, int w, int h, float f, Rgba fg, Rgba bg) {
    f = f < 0 ? 0 : (f > 1 ? 1 : f);
    fill_rect(x, y, w, h, bg);
    fill_rect(x, y, int(float(w) * f + 0.5f), h, fg);
}

int Canvas::text(int x, int y, const std::string& s, int scale, Rgba c) {
    int cx = x;
    for (char ch : s) {
        const Glyph* g = glyph_or_fallback(ch);
        for (int r = 0; r < 7; ++r)
            for (int col = 0; col < 5; ++col)
                if (g->rows[r][col] == '#') fill_rect(cx + col * scale, y + r * scale, scale, scale, c);
        cx += 6 * scale;
    }
    return cx - x;
}

int Canvas::text_width(const std::string& s, int scale) { return int(s.size()) * 6 * scale; }

int Canvas::text_fit(int x, int y, const std::string& s, int scale, Rgba c, int max_w) {
    if (text_width(s, scale) <= max_w) return text(x, y, s, scale, c);
    std::string t = s;
    while (!t.empty() && text_width(t + "...", scale) > max_w) t.pop_back();
    return text(x, y, t + "...", scale, c);
}

bool Canvas::save_ppm(const std::string& path) const {
    FILE* f = fopen(path.c_str(), "wb");
    if (!f) return false;
    fprintf(f, "P6\n%d %d\n255\n", w_, h_);
    for (size_t i = 0; i < px_.size(); i += 4) fwrite(&px_[i], 1, 3, f);
    fclose(f);
    return true;
}

