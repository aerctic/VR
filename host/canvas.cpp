const Glyph* glyph(char c) {
    c = char(std::toupper(static_cast<unsigned char>(c)));
    for (const Glyph& g : kFont)
        if (g.c == c) return &g;
    return nullptr;
}

const Glyph* glyph_or_fallback(char c) {
    const Glyph* g = glyph(c);
    return g ? g : glyph('?');
}

